#!/usr/bin/env node
// tools/seed-demo.cjs — fill the LOCAL D1 database with plausible guest traffic.
//
//   node tools/seed-demo.cjs
//
// Why: the dashboards are honest about an empty database, which is right for
// production and useless for looking at the panel. This writes ~500 messages,
// ~40 escalations and ~120 AI interactions across three properties so every tab
// has something real to render.
//
// Safety:
//   * Always `--local`. Production D1 is never touched; the flag is hardcoded.
//   * Only its own three properties are deleted and rewritten, so other local
//     data survives.
//   * Deterministic: the same seed produces the same numbers, so screenshots and
//     tests stay comparable between runs.
//
// Guest numbers are 555 numbers and message bodies are obviously fake.

const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");

const DB = "davenport-host-co-db";
const DAYS = 60;

// Deterministic LCG so re-running gives the same picture.
let state = 20261026;
function rand() {
  state = (state * 1103515245 + 12345) % 2147483648;
  return state / 2147483648;
}
function pick(list) {
  return list[Math.floor(rand() * list.length)];
}
function between(min, max) {
  return min + Math.floor(rand() * (max - min + 1));
}

const HOST = { id: "host_dana", name: "Dana", phone: "+18635550100", email: "dana@example.com" };

const PROPERTIES = [
  { id: "SUNSET", name: "Sunset Villa", number: "+18635550142", weight: 0.42 },
  { id: "HARBOR", name: "Harbor House", number: "+18635550143", weight: 0.34 },
  { id: "LAKEVIEW", name: "Lakeview Lodge", number: "+18635550144", weight: 0.24 },
];

const INTENTS = [
  { key: "wifi", weight: 0.24, text: "What is the wifi password?" },
  { key: "checkout", weight: 0.18, text: "What time is checkout?" },
  { key: "gate", weight: 0.16, text: "What is the gate code?" },
  { key: "trash", weight: 0.12, text: "When does the trash get collected?" },
  { key: "pool_heat", weight: 0.12, text: "How do I turn on the pool heater?" },
  { key: "parking", weight: 0.08, text: "Where do we park the second car?" },
  { key: "checkin", weight: 0.06, text: "Can we check in a little early?" },
  { key: "pets", weight: 0.04, text: "Are dogs allowed here?" },
];

// Resolutions, weighted. `escalated` rows also produce an escalation record.
const RESOLUTIONS = [
  { key: "keyword", weight: 0.38 },
  { key: "kb", weight: 0.14 },
  { key: "ai", weight: 0.3 },
  { key: "escalated", weight: 0.11 },
  { key: "unrouted", weight: 0.07 },
];

function weighted(list) {
  const total = list.reduce((sum, item) => sum + item.weight, 0);
  let roll = rand() * total;
  for (const item of list) {
    roll -= item.weight;
    if (roll <= 0) return item;
  }
  return list[list.length - 1];
}

function stamp(date) {
  return date.toISOString().slice(0, 19).replace("T", " ");
}

function q(value) {
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function buildSql() {
  const lines = [];
  const now = Date.now();
  const since = now - DAYS * 86400000;

  lines.push("-- generated by tools/seed-demo.cjs");
  lines.push("DELETE FROM ai_interactions WHERE property_id IN ('SUNSET','HARBOR','LAKEVIEW');");
  lines.push("DELETE FROM escalations WHERE property_id IN ('SUNSET','HARBOR','LAKEVIEW');");
  lines.push("DELETE FROM messages WHERE property_id IN ('SUNSET','HARBOR','LAKEVIEW');");
  lines.push("DELETE FROM properties WHERE id IN ('SUNSET','HARBOR','LAKEVIEW');");
  lines.push("DELETE FROM hosts WHERE id = 'host_dana';");

  lines.push(
    "INSERT INTO hosts (id, name, phone, email, active) VALUES (" +
      [HOST.id, HOST.name, HOST.phone, HOST.email].map(q).join(", ") +
      ", 1);",
  );

  for (const property of PROPERTIES) {
    // No address column: the migrations never added one, even though schema.sql
    // has it, so the local database and a fresh production setup differ here.
    lines.push(
      "INSERT INTO properties (id, house_code, display_name, host_id, twilio_number, active) VALUES (" +
        [property.id, property.id, property.name, HOST.id, property.number].map(q).join(", ") +
        ", 1);",
    );
  }

  let messages = 0;
  let escalations = 0;
  let aiRows = 0;
  let guestCounter = 0;

  for (let day = DAYS; day >= 0; day -= 1) {
    const weekday = new Date(now - day * 86400000).getUTCDay();
    // Busier at weekends, like real short-let traffic.
    const base = weekday === 0 || weekday === 6 ? 11 : 7;
    const volume = Math.max(0, base + between(-3, 3));

    for (let i = 0; i < volume; i += 1) {
      const property = weighted(PROPERTIES);
      const intent = weighted(INTENTS);
      const resolution = weighted(RESOLUTIONS);
      guestCounter += 1;
      const guest = "+1555010" + String(1000 + guestCounter).slice(-4);
      const thread = "thr_" + property.id.toLowerCase() + "_" + day + "_" + i;
      // Today's traffic must not land in the future: naive "hour 7-22 of the
      // current day" put the newest rows up to 17h ahead of the clock, which the
      // awaiting query then reported as a negative age. Pull anything that would
      // cross now back into the last few hours.
      const scheduled = since + (DAYS - day) * 86400000 + between(7, 22) * 3600000 + between(0, 59) * 60000;
      const inboundAt = new Date(
        scheduled > now - 60000 ? now - between(1, 240) * 60000 : scheduled,
      );

      lines.push(
        "INSERT INTO messages (created_at, direction, property_id, from_number, body, body_redacted, thread_id, intent_key, risk, resolution) VALUES (" +
          [
            stamp(inboundAt),
            "in",
            property.id,
            guest,
            intent.text,
            intent.text,
            thread,
            intent.key,
            intent.key === "gate" ? "high" : "low",
            resolution.key,
          ].map(q).join(", ") +
          ");",
      );
      messages += 1;

      // Every message that got an automated answer got a reply.
      if (resolution.key === "keyword" || resolution.key === "kb" || resolution.key === "ai") {
        lines.push(
          "INSERT INTO messages (created_at, direction, property_id, from_number, body, body_redacted, thread_id, intent_key, risk, resolution) VALUES (" +
            [
              stamp(new Date(inboundAt.getTime() + between(3, 40) * 1000)),
              "out",
              property.id,
              property.number,
              "Reply sent to the guest.",
              "Reply sent to the guest.",
              thread,
              intent.key,
              "low",
              resolution.key,
            ].map(q).join(", ") +
            ");",
        );
        messages += 1;
      }

      if (resolution.key === "ai") {
        lines.push(
          "INSERT INTO ai_interactions (created_at, property_id, house_code, thread_id, model, conversation_context, prompt, response, outcome, latency_ms, tokens_in, tokens_out) VALUES (" +
            [
              stamp(inboundAt),
              property.id,
              property.id,
              thread,
              "openai/gpt-4o-mini",
              "guest question",
              intent.text,
              "answered from property knowledge",
              "answered",
              between(650, 2400),
              between(180, 620),
              between(40, 160),
            ].map(q).join(", ") +
            ");",
        );
        aiRows += 1;
      }

      if (resolution.key === "escalated") {
        // Only recent escalations stay open. A 0.05 chance on every old day left
        // a question unanswered for six weeks, which is not the healthy-but-busy
        // panel this is supposed to show.
        const openChance = day <= 1 ? 0.7 : day <= 2 ? 0.3 : 0;
        const isOpen = rand() < openChance;
        const answeredAt = new Date(inboundAt.getTime() + between(4, 95) * 60000);
        lines.push(
          "INSERT INTO escalations (created_at, property_id, guest_number, question, status, host_number, host_notified, thread_id, answered_at, answer_body) VALUES (" +
            [
              stamp(inboundAt),
              property.id,
              guest,
              intent.text,
              isOpen ? "open" : "answered",
              HOST.phone,
              1,
              thread,
              isOpen ? null : stamp(answeredAt),
              isOpen ? null : "Host replied directly.",
            ]
              .map((value) => (value === null ? "NULL" : q(value)))
              .join(", ") +
            ");",
        );
        escalations += 1;
      }
    }

    // Keep the open queue from being empty: the newest day gets a couple of
    // young, unanswered questions whatever the dice said.
    if (day === 0) {
      for (const aged of [17, 48, 96]) {
        const property = PROPERTIES[aged % PROPERTIES.length];
        guestCounter += 1;
        const guest = "+1555010" + String(1000 + guestCounter).slice(-4);
        lines.push(
          "INSERT INTO escalations (created_at, property_id, guest_number, question, status, host_number, host_notified, thread_id) VALUES (" +
            [
              stamp(new Date(now - aged * 60000)),
              property.id,
              guest,
              "Late checkout request",
              "open",
              HOST.phone,
              1,
              "thr_open_" + aged,
            ].map(q).join(", ") +
            ");",
        );
        escalations += 1;
      }
    }
  }

  return { sql: lines.join("\n") + "\n", counts: { messages, escalations, aiRows } };
}

function main() {
  if (process.argv.includes("--remote")) {
    console.error("Refusing to run: this seeder is local-only by design.");
    process.exit(1);
  }

  const { sql, counts } = buildSql();
  const file = path.join(os.tmpdir(), "stayxi-seed-" + Date.now() + ".sql");
  fs.writeFileSync(file, sql);
  console.log(
    "generated " + counts.messages + " messages, " + counts.escalations + " escalations, " +
      counts.aiRows + " AI interactions (" + Math.round(sql.length / 1024) + " KB)",
  );

  const result = spawnSync(
    process.platform === "win32" ? "npx.cmd" : "npx",
    ["wrangler", "d1", "execute", DB, "--local", "--file=" + file],
    { encoding: "utf8", shell: true, timeout: 180000 },
  );
  const output = (result.stdout || "") + (result.stderr || "");
  if (result.status !== 0) {
    console.error("wrangler d1 execute failed:\n" + output.split("\n").slice(-15).join("\n"));
    process.exit(1);
  }
  console.log("seeded the local database");

  // Run the summary from a file: inline SQL loses its quoting when spawned
  // through a shell on Windows.
  const checkFile = file.replace(/\.sql$/, "-check.sql");
  fs.writeFileSync(
    checkFile,
    "SELECT (SELECT COUNT(*) FROM messages) AS messages,\n" +
      "       (SELECT COUNT(*) FROM escalations WHERE status = 'open') AS open_escalations,\n" +
      "       (SELECT COUNT(*) FROM properties WHERE active = 1) AS live_properties;\n",
  );
  const check = spawnSync(
    process.platform === "win32" ? "npx.cmd" : "npx",
    ["wrangler", "d1", "execute", DB, "--local", "--file=" + checkFile],
    { encoding: "utf8", shell: true, timeout: 120000 },
  );
  const text = (check.stdout || "") + (check.stderr || "");
  const read = (key) => {
    const match = text.match(new RegExp('"' + key + '":\\s*(\\d+)'));
    return match ? match[1] : "?";
  };
  console.log(
    "local database now holds " + read("messages") + " messages, " + read("open_escalations") +
      " open escalations, " + read("live_properties") + " live properties",
  );
}

main();
